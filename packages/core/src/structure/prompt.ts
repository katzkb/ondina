// 構成の推定（設計書 10.6）で LLM コマンドに stdin で渡すプロンプト本文。label/prompt.ts と同じく、
// CLI 固有のフラグに頼らず、指示・出力の形・入力 JSON をすべてこの本文に入れる。決定的（同じ入力には同じ本文。原則 7）。
import { STRUCTURE_OUTPUT_SCHEMA } from './schema.js';
import type { StructureInput } from './types.js';

const INSTRUCTIONS = `あなたはコードレビューの道具の一部です。リポジトリのファイルの一覧から、このリポジトリのコードがどんな層に分かれているかを推定します。結果は、レビューで変更を層ごとの帯に並べた地図を描くのに使います。人の代わりに判断はしません。

守ること:
- 正しさ・設計の良し悪しについての意見を書かない。評価語（良い / 悪い / 適切 / 違反 など）を使わない
- ファイルを読まない。ツールを使わない。コマンドを実行しない。入力 JSON にある情報だけで答える
- 返答は下の JSON Schema に合う JSON オブジェクト 1 つだけ。前後に文やコードフェンスを付けない。why は日本語で 1 行

入力:
- dirs はディレクトリごとのファイル名。"." はリポジトリ直下のファイルだけ（下のディレクトリは含まない）。decls は .kt ファイルの最上位の宣言（種別と名前）

layers（層）:
- このリポジトリのコードを 3〜8 個の層に分ける。よくある名前の決まりに当てはめず、このリポジトリのディレクトリ名・ファイル名・宣言の名前から読み取れる分け方にする。名前もこのリポジトリの言葉を使う
- 呼ぶ側を上、呼ばれる側を下に並べる（例: 外からの入口 → 処理の流れ → データの置き場）
- テストのコードがあれば、それも 1 つの層にしてよい

dirs / files（振り分け）:
- ディレクトリ丸ごと同じ層なら dirs に { dir, layer } で書く。下のディレクトリも含む（"." だけは直下のファイルだけ）。より深いディレクトリを別の層にしてよい（深いほうが勝つ）
- 同じディレクトリの中で層が分かれるときだけ、files に { path, layer } でファイルを書く（ファイルが勝つ）
- dir と path は入力にあるものを使う。layer は layers の name のどれか

outside（対象外）:
- コードの構成に入らないディレクトリ（文書・ビルド設定・CI の設定など）を書く。後から増えたファイルのうち、ここにも層にも入らないものを「分類できないファイル」として数える
- どれにも当てはめられないものは書かずに残す

tests（テストの置き場）:
- テストのコード（テストと、テストだけが使う補助）があるディレクトリを書く。下のディレクトリも含む。リポジトリ全体（"."）は書かない
- テストと本体のコードが同じディレクトリに混ざるときは、テストのファイルを path で書く
- テストのコードがなければ空の配列にする
- dirs / files の層の振り分けとは別に書く（テストのディレクトリが層の振り分けにも入っていてよい）`;

const PREVIOUS_INSTRUCTIONS = `previous（推定し直し）:
- previous.layers は前回推定した層の名前（上から）。今のファイルにも当てはまる層は、同じ名前と同じ並びを使う。当てはまらない層は落とし、新しい層は足してよい`;

export function renderStructurePrompt(input: StructureInput): string {
  const parts = [INSTRUCTIONS];
  if (input.previous !== undefined) parts.push(PREVIOUS_INSTRUCTIONS);
  parts.push(`出力の形（JSON Schema）:\n${JSON.stringify(STRUCTURE_OUTPUT_SCHEMA, null, 2)}`, `入力:\n${JSON.stringify(input, null, 2)}`);
  return parts.join('\n\n') + '\n';
}
