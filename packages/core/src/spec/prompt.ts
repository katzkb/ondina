// 要求の抜き出し（設計書 10.8）に stdin で渡すプロンプト本文。決定的（同じ入力には同じ本文。原則 7）。
// 1 回目（label/prompt.ts）と同じく、CLI 固有のフラグに頼らず、指示・出力の形・入力 JSON をすべてこの本文に入れる。
// LLM は要求を抜き出し、対応する How を入力の How から選ぶだけ。対応の有無と数はプログラムが決める（原則 3）。
// 例文は別の題材で書く（fixture の記録を、チケットの文に寄せて見せかけない）。
import { SPEC_OUTPUT_SCHEMA } from './schema.js';
import type { SpecInput } from './types.js';

const INSTRUCTIONS = `あなたはコードレビューの道具の一部です。チケット（課題管理の項目）から「この PR で成り立つべきこと」を抜き出し、それぞれに対応する目的（How）を選びます。あわせて、チケットに書かれた「なぜこの変更をするか」の文と、親チケット（このチケットを含む案件）に書かれた案件の目的の文を写します。結果は、レビューする人が要求と変更の対応を確かめる画面と、PR の背景を読む画面に出します。人の代わりに判断はしません。

守ること:
- 正しさ・バグ・品質についての意見を書かない。評価語（良い / 悪い / 適切 / 不足 / 漏れ など）を使わない
- ファイルを読まない。ツールを使わない。コマンドを実行しない。入力 JSON にある情報だけで答える
- 返答は下の JSON Schema に合う JSON オブジェクト 1 つだけ。前後に文やコードフェンスを付けない。文字列は日本語で書く

specs（チケットから抜き出した要求）:
- ticket の title と body から、この PR で成り立つべきこと（できるようになること・振る舞い・完了の条件）を 1 項目に 1 つずつ抜き出す
- 背景・経緯・目的の説明・担当や期日は入れない。チケットに書かれていないことを足さない
- チケットに書かれた順に並べる。10 個まで。同じことを 2 回書かない
- text は短い 1 文。句点を付けない（画面はリストで出す）。チケットの言葉と値（名前・数値・パス）はそのまま使ってよい
- 要求が書かれていなければ specs は空の配列

hows（要求ごとに対応する目的）:
- 入力の hows[].id から選ぶ。それ以外の数を書かない
- その要求が述べる振る舞いを足す・変える差分が、その How にあるときだけ入れる（hunkIds の hunks[] と groupIds の rippleGroups[] の行を読む）
- 同じ領域なだけ・関係するだけの How は入れない
- 対応する How がなければ空の配列。満たしているか・十分かは書かない（書くのは対応の有無だけ）

why（チケットに書かれた「なぜこの変更をするか」）:
- ticket の body から、この変更をする理由・きっかけ・目的を述べる文を、原文のまま写す。1〜3 文。1 文を配列の 1 要素にする
- 言い換えない。要約しない。句点までの 1 文を丸ごと写す（文の一部だけを切り出さない）
- やること・完了の条件（specs に入るもの）は入れない
- 理由・きっかけ・目的が書かれていなければ空の配列

parentWhy（親チケットに書かれた「この案件の目的」）:
- parent の body から、この案件をする目的・理由・きっかけを述べる文を、原文のまま写す。1〜3 文。1 文を配列の 1 要素にする
- 言い換えない。要約しない。句点までの 1 文を丸ごと写す（文の一部だけを切り出さない）
- 子のチケットの一覧・やること・担当・期日は入れない。ticket の body の文は入れない
- parent がないか、目的が書かれていなければ空の配列

previous（ある場合）:
- 前回の解析で同じチケットから抜き出した要求。チケットの同じ要求は同じ文で書く。差分が変わっていなければ、対応する How も同じにする

入力の読み方:
- hunks[].lines と rippleGroups[] の representative.lines / deviations[].lines は差分の行。1 文字目が "+" は追加、"-" は削除、" " は前後の文脈
- rippleGroups[] は同じ形の書き換えの束（members は同じ形の件数。行はサンプルと、サンプルと差異のある場所だけ）
- ticket.truncated（parent.truncated）が true なら本文は途中で切ってある

例（題材は別のチケット。形だけを真似る）:
- text: 「在庫を倉庫ごとに引き当てられる」「在庫が足りなければ引き当てない」
- 対応する How がない要求: { "text": "倉庫を指定しない引き当ては 400 を返す", "hows": [] }
- why: ["月末の棚卸しで、倉庫ごとの在庫が帳簿と合わない。", "今は全倉庫の合計しか持っていない。"]
- parentWhy: ["今期中に、月末の棚卸しを 1 日で終えられるようにする。"]`;

export function renderSpecPrompt(input: SpecInput): string {
  return [INSTRUCTIONS, `出力の形（JSON Schema）:\n${JSON.stringify(SPEC_OUTPUT_SCHEMA, null, 2)}`, `入力:\n${JSON.stringify(input, null, 2)}`].join('\n\n') + '\n';
}
